"""Live Sarvam STT Real Speech Verification Test.

This test MUST NOT BE MOCKED.
It uses `real_speech.mp3` to verify real STT transcription quality
and pipeline handoff.
"""

import logging
import os
import time
import uuid

import pytest

logger = logging.getLogger(__name__)

SARVAM_API_KEY = os.environ.get("SARVAM_API_KEY", "")
skip_reason = "SARVAM_API_KEY not configured — skipping live real speech test"


@pytest.mark.skipif(not SARVAM_API_KEY, reason=skip_reason)
@pytest.mark.asyncio
async def test_real_speech_pipeline_handoff():
    from sqlalchemy.future import select

    import app.workers.stt_worker as sw
    from app.core.config import settings
    from app.infrastructure.database.session import AsyncSessionLocal
    from app.infrastructure.storage.s3_storage import storage_client
    from app.models.communication import (
        CommunicationAttachment,
        CommunicationMessage,
        CommunicationTranscript,
        ExtractedEventCandidate,
    )
    from tests.test_webhooks import setup_integration

    # 1. Read the audio generated by gTTS
    audio_path = "/app/real_speech.mp3"
    if not os.path.exists(audio_path):
        pytest.fail(f"Audio file {audio_path} not found inside container.")

    with open(audio_path, "rb") as f:
        audio_bytes = f.read()

    # 2. Setup DB integration
    company_id = await setup_integration(
        company_name=f"Real Speech Test {uuid.uuid4()}",
        phone_number_id=f"rs_{uuid.uuid4()}",
    )

    msg_id = str(uuid.uuid4())
    object_key = f"{company_id}/evidence/{msg_id}/test.mp3"
    await storage_client.upload(settings.MINIO_BUCKET, object_key, audio_bytes)

    async with AsyncSessionLocal() as db:
        msg = CommunicationMessage(
            id=msg_id,
            company_id=company_id,
            source_channel="WHATSAPP",
            external_message_id=f"ext_{msg_id}",
            sender_identity="+111",
            status="RECEIVED",
        )
        db.add(msg)
        att = CommunicationAttachment(
            id=str(uuid.uuid4()),
            message_id=msg_id,
            media_type="audio/mpeg",
            object_storage_key=object_key,
            file_size=len(audio_bytes),
            status="MEDIA_PERSISTED",
        )
        db.add(att)
        await db.flush()

        transcript = CommunicationTranscript(
            id=str(uuid.uuid4()),
            company_id=company_id,
            attachment_id=att.id,
            provider="sarvam",
            model="saaras:v4",
            status="PENDING",
        )
        db.add(transcript)
        await db.commit()
        t_id = transcript.id

    # 3. Ensure the provider is lazily loaded using the real key
    # We DO NOT mock the provider. We make sure _provider is None so it inits
    sw._provider = None

    # 4. Run the worker
    start = time.monotonic()
    result = await sw.process_one_transcript("worker-real-speech")
    latency_ms = int((time.monotonic() - start) * 1000)

    assert result is True, "Worker should have found and processed a transcript"

    # 5. Verify the results
    async with AsyncSessionLocal() as db:
        t_result = await db.execute(
            select(CommunicationTranscript).where(CommunicationTranscript.id == t_id)
        )
        t = t_result.scalars().first()

        # Verify extraction handoff
        ext_result = await db.execute(
            select(ExtractedEventCandidate).where(
                ExtractedEventCandidate.transcript_id == t_id
            )
        )
        extraction_candidate = ext_result.scalars().first()

        logger.info(
            "=== FINAL STT QUALITY VERIFICATION ===\n"
            f"1. Audio duration: {t.duration_seconds}s\n"
            f"2. Provider: {t.provider}\n"
            f"3. Model: {t.model}\n"
            f"4. API request success: {'YES' if t.status == 'COMPLETED' else 'NO (' + t.status + ')'}\n"
            f"6. Transcript returned: {'YES' if t.provider_transcript else 'NO'}\n"
            f"7. Actual transcript text: '{t.provider_transcript}'\n"
            f"8. Processing latency: {latency_ms} ms\n"
            f"9. Transcript persistence: {'PASS' if t.status == 'COMPLETED' and t.provider_transcript else 'FAIL'}\n"
            f"10. Extraction handoff received: {'YES' if extraction_candidate else 'NO'}"
        )

        assert t.status == "COMPLETED"
        assert t.provider_transcript is not None
        assert extraction_candidate is not None
        assert extraction_candidate.processing_status == "PENDING"
